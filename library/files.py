"""Filename handling for untrusted uploads.

Kept free of model imports so both models and services can use it without
circular dependencies. Sanitized names are display metadata only — storage
paths are always generated by Django's FileField/storage stack.
"""

import os
import re

_FILENAME_UNSAFE = re.compile(r"[^A-Za-z0-9._ -]")


def sanitize_original_filename(name):
    """Return a display-safe version of a client-supplied filename."""
    base = os.path.basename((name or "").replace("\\", "/")).strip()
    base = _FILENAME_UNSAFE.sub("_", base)
    return base[:255]