"""Filename handling and private file serving.

Kept free of model imports so both models and services can use it without
circular dependencies. Sanitized names are display metadata only; storage
paths are always generated by Django's FileField/storage stack.

build_file_response serves private files with hardening (nosniff, CORP,
private no-store, sandboxing CSP on inline reads), and conditional/range
support (ETag, Last-Modified, Accept-Ranges) so viewers can seek without
re-downloading a multi-MB PDF.
"""

import hashlib
import os
import re
from email.utils import formatdate
from zoneinfo import ZoneInfo

from django.conf import settings
from django.http import FileResponse, HttpResponse

_FILENAME_UNSAFE = re.compile(r"[^A-Za-z0-9._ -]")


def sanitize_original_filename(name):
    """Return a display-safe version of a client-supplied filename."""
    base = os.path.basename((name or "").replace("\\", "/")).strip()
    base = _FILENAME_UNSAFE.sub("_", base)
    return base[:255]


class _RangeReader:
    """A file-like slice so a Range request streams only its requested bytes."""

    def __init__(self, fileobj, start, length, chunk=64 * 1024):
        self.fileobj = fileobj
        self.fileobj.seek(start)
        self.remaining = length
        self.chunk = chunk

    def read(self, n=-1):
        if self.remaining <= 0:
            return b""
        amount = min(self.chunk, self.remaining) if n < 0 else min(n, self.chunk, self.remaining)
        data = self.fileobj.read(amount)
        self.remaining -= len(data)
        return data

    def close(self):
        self.fileobj.close()


def _posix_mtime(storage, name):
    modified = storage.get_modified_time(name)
    if modified is None:
        return 0
    if modified.tzinfo is None:
        modified = modified.replace(tzinfo=ZoneInfo("UTC"))
    return modified.astimezone(ZoneInfo("UTC")).timestamp()


def _apply_hardening(response, disposition):
    response["X-Content-Type-Options"] = "nosniff"
    response["Cross-Origin-Resource-Policy"] = "same-origin"
    response["Cache-Control"] = "private, no-store"
    if disposition == "inline":
        response["Content-Security-Policy"] = "default-src 'none'; sandbox"
    return response


def build_file_response(request, resource, disposition, filename):
    """Serve a private file with hardening + conditional/Range support.

    Returns an X-Accel-Redirect response when LIBRARY_XACCEL_ENABLED is set,
    so the app server does not stream file bytes in production.
    """
    storage = resource.file.storage
    name = resource.file.name
    size = resource.file_size or storage.size(name)
    mtime = _posix_mtime(storage, name)
    etag = f'"{hashlib.md5(f"{name}:{size}".encode()).hexdigest()}"'
    last_modified = formatdate(mtime, usegmt=True)

    if getattr(settings, "LIBRARY_XACCEL_ENABLED", False):
        prefix = getattr(settings, "LIBRARY_INTERNAL_PATH_PREFIX", "/internal")
        response = HttpResponse(content_type="application/pdf")
        _apply_hardening(response, disposition)
        response["X-Accel-Redirect"] = f"{prefix}/{name}"
        return response

    etags = [
        tag.strip()
        for tag in request.META.get("HTTP_IF_NONE_MATCH", "").split(",")
        if tag.strip()
    ]
    if etags and (etag in etags or "*" in etags):
        response = HttpResponse(status=304)
        response["ETag"] = etag
        return response

    if request.META.get("HTTP_IF_MODIFIED_SINCE"):
        try:
            from email.utils import parsedate_to_datetime

            if mtime <= parsedate_to_datetime(request.META["HTTP_IF_MODIFIED_SINCE"]).timestamp():
                response = HttpResponse(status=304)
                response["ETag"] = etag
                response["Last-Modified"] = last_modified
                return response
        except (TypeError, ValueError):
            pass

    range_header = request.META.get("HTTP_RANGE", "")
    match = re.fullmatch(r"bytes=(\d*)\s*-\s*(\d*)", range_header.strip())
    if range_header and not match:
        response = HttpResponse(status=416)
        response["Content-Range"] = f"bytes */{size}"
        return response

    file = resource.file.open("rb")
    status = 200
    reader = file
    content_range = None
    if match is not None:
        start = int(match.group(1)) if match.group(1) else 0
        end = int(match.group(2)) if match.group(2) else size - 1
        end = min(end, size - 1)
        if start >= size or start > end:
            file.close()
            response = HttpResponse(status=416)
            response["Content-Range"] = f"bytes */{size}"
            return response
        reader = _RangeReader(file, start, end - start + 1)
        status = 206
        content_range = f"bytes {start}-{end}/{size}"

    response = FileResponse(
        reader,
        status=status,
        content_type="application/pdf",
        as_attachment=disposition == "attachment",
    )
    response["Content-Disposition"] = f'{disposition}; filename="{filename}"'
    response["ETag"] = etag
    response["Last-Modified"] = last_modified
    response["Accept-Ranges"] = "bytes"
    if content_range:
        response["Content-Range"] = content_range
    return _apply_hardening(response, disposition)